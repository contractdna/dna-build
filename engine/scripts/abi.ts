// Generates src/abi.ts from Foundry artifacts (run `forge build` in contracts/ first).
// `node scripts/abi.ts --check` exits 1 if the committed file drifted from the artifacts.
import { readFileSync, writeFileSync } from "node:fs";

const out = new URL("../../contracts/out/", import.meta.url);
const target = new URL("../src/abi.ts", import.meta.url);

const read = (file: string, name = file) =>
  JSON.parse(readFileSync(new URL(`${file}.sol/${name}.json`, out), "utf8")).abi as { type: string; name?: string }[];

const abis: Record<string, unknown[]> = {
  registryAbi: read("ModuleRegistry"),
  hookAbi: read("DNAHook"),
  feeVaultAbi: read("FeeVault"),
  buybackBurnAbi: read("BuybackBurn"),
  liquidityVaultAbi: read("LiquidityVault"),
  platformRevenueAbi: read("PlatformRevenue"),
  tokenAbi: read("DNAToken"),
  ideaMarketAbi: read("IdeaMarket"),
  bountyBoardAbi: read("BountyBoard"),
  // the game layer (SPEC §12–§14): keepers, agent tasks, indexer
  gamePotAbi: read("GamePot"),
  convictionVaultAbi: read("ConvictionVault"),
  mutationBoardAbi: read("MutationBoard"),
  // the Sequencer's games: the factory (GameDeployed, GameRetired), every game's kit events (Played, Funded, ...) and
  // the ladder's GameFunder (funding)
  gameFactoryAbi: read("GameFactory"),
  gameKitAbi: read("GameKit"),
  gameFunderAbi: read("GameFunder"),
  // the Genome Vaults NFT: Minted / Funded / Burned feed the indexer, the site's news and X
  genomeVaultsAbi: read("GenomeVaults"),
  // PoolManager: only what the engine touches (Swap logs, ERC-6909 claim balances)
  poolManagerAbi: read("PoolManager").filter((x) => (x.type === "event" && x.name === "Swap") || (x.type === "function" && x.name === "balanceOf")),
  // v4-core's test router: the simulator deploys it on its anvil fork to replay recorded swaps (src/sim.ts)
  poolSwapTestAbi: read("PoolSwapTest").filter((x) => x.type === "function" && x.name === "swap"),
};
const bytecode = JSON.parse(readFileSync(new URL("PoolSwapTest.sol/PoolSwapTest.json", out), "utf8")).bytecode.object as string;

const src = "// GENERATED by engine/scripts/abi.ts from contracts/out. Do not edit; run `npm run abi` after `forge build`.\n" +
  Object.entries(abis).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)} as const;\n`).join("") +
  `export const poolSwapTestBytecode = "${bytecode}";\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== src) { console.error("src/abi.ts is stale: run `npm run abi`"); process.exit(1); }
  console.log("src/abi.ts up to date");
} else {
  writeFileSync(target, src);
  console.log("wrote src/abi.ts");
}
